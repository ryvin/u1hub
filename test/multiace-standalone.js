// M109/T, the config block at the tail with filament_colour ';'-joined, a
// 5x5 flush_volumes_matrix and 4 per-extruder nozzle_diameter entries.
const MATRIX = [0, 500, 753, 652, 634, 182, 0, 632, 678, 408, 219, 348, 0, 399, 223, 172, 354, 326, 0, 339, 199, 224, 406, 549, 0];
const COLORS = ["#000000", "#FF0000", "#FFFF00", "#FFFFFF", "#FF8000"];
const EVENTS = [0, 1, 4, 2, 3, 0, 4];
function gcode(o) {
  const op = o || {};
  const colors = op.colors || COLORS, types = op.types || colors.map(() => "PLA"), events = op.events || EVENTS;
  let s = "; HEADER_BLOCK_START\n; generated by Snapmaker Orca 2.2.1 on 2026-01-28 at 17:00:56\n; total layer number: 24\n; filament_density: " + colors.map(() => "1.24").join(",") + "\n; filament_diameter: " + colors.map(() => "1.75").join(",") + "\n; HEADER_BLOCK_END\n\n";
  if (op.processed) s += "; multiACE auto-load: load 4 head(s)\n; multiACE processed: format=4\nACE_SET_PURGE RESET=1\nACE_SWAP_HEAD HEAD=0 ACE=1 SLOT=0 INITIAL=1\n; multiACE auto-load: end\n";
  s += "M73 P0 R182\nG28\nG90\nM83\n";
  let prev = events[0];
  events.forEach((t, i) => {
    if (!op.noMarkers) s += "; Change Tool" + prev + " -> Tool" + t + " (layer " + (i - 1) + ")\n";
    s += "M109 S220 T" + t + "\nM400\nT" + t + "\nSM_PRINT_PREEXTRUDE_FILAMENT INDEX=" + t + "\n";
    if (!op.noMarkers) s += "; LAYER_CHANGE\n; Z:" + (0.2 * (i + 1)).toFixed(2) + "\n";
    for (let k = 0; k < 20; k++) s += "G1 X" + (10 + k) + " Y" + (10 + k) + " E0.5 F1800\n";
    prev = t;
  });
  const used = new Set(events);
  s += "; CONFIG_BLOCK_START\n; filament_colour = " + colors.join(";") + "\n; filament_density = " + colors.map(() => "1.24").join(",") + "\n; filament_type = " + types.join(";") + "\n";
  s += "; filament used [g] = " + colors.map((c, i) => used.has(i) ? "5.00" : "0.00").join(", ") + "\n; total filament used [g] = " + (used.size * 5).toFixed(2) + "\n; estimated printing time (normal mode) = 3h 2m\n";
  s += "; flush_multiplier = " + (op.mult == null ? 1 : op.mult) + "\n; flush_volumes_matrix = " + (op.matrix || MATRIX).join(",") + "\n; nozzle_diameter = " + (op.nozzle || "0.4,0.4,0.4,0.4") + "\n";
  if (op.fs) s += "; mixed_filament_definitions = 1,2,1,1,50,0,g12,w,m0,u1,cm0\n";
  s += "; printer_settings_id = Snapmaker U1 (0.4 nozzle) - HueForge\n; CONFIG_BLOCK_END\n";
  return s;
}

